export const photoById = Object.fromEntries(photos.filter((p) => p.id).map((p) => [p.id, p]))

const PLACEHOLDER_SRC = /^\/assets\/photos\/photo\d+\./i

export function isLinkedPhoto(photo) {
  const src = photo?.src
  if (!src || typeof src !== 'string') return false
  if (/^[a-zA-Z]:[\\/]/.test(src)) return false
  if (PLACEHOLDER_SRC.test(src)) return false
  return src.startsWith('/assets/')
}

export function getPhoto(id) {
  return photoById[id] || null
}
